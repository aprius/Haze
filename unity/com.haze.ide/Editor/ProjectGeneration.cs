using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security;
using System.Security.Cryptography;
using System.Text;
using UnityEditor;
using UnityEditor.Compilation;
using UnityEngine;
using PackageInfo = UnityEditor.PackageManager.PackageInfo;

namespace Haze.Ide.Editor
{
    /// <summary>
    /// Writes an SDK-style .csproj per script assembly (the format the Roslyn
    /// language server loads) and a .sln listing them, from Unity's own view
    /// of the compilation: sources, defines, references, response files and
    /// analyzers.
    /// </summary>
    static class ProjectGeneration
    {
        const string k_Marker = "<!-- Generated by Haze (com.haze.ide); changes are overwritten. -->";
        static readonly string[] k_Watched = { ".cs", ".asmdef", ".asmref", ".rsp", ".dll", ".additionalfile" };

        public static string ProjectDirectory => Directory.GetParent(Application.dataPath).FullName;
        static string ProjectName => Path.GetFileName(ProjectDirectory);
        public static string SolutionPath => Path.Combine(ProjectDirectory, ProjectName + ".sln");

        public static bool Affects(IEnumerable<string> paths) =>
            paths.Any(p => k_Watched.Contains(Path.GetExtension(p).ToLowerInvariant()));

        /// <summary>An assembly and the project written for it: "Name.Player" for its player build.</summary>
        class Project
        {
            public string Name;
            public Assembly Assembly;
            public bool Player;
        }

        public static void Sync()
        {
            s_Packages.Clear();
            s_UnityAnalyzers = Settings.Flags.HasFlag(GenerationFlags.UnityAnalyzers) ? BundledUnityAnalyzers() : null;
            var projects = Projects(AssembliesType.Editor, "").ToList();
            if (Settings.Flags.HasFlag(GenerationFlags.PlayerProjects))
                projects.AddRange(Projects(AssembliesType.Player, ".Player"));
            projects.Sort((a, b) => string.CompareOrdinal(a.Name, b.Name));

            // Assemblies with a project, editor and player apart: references to them become project references.
            var editorNames = new HashSet<string>(projects.Where(p => !p.Player).Select(p => p.Assembly.name));
            var playerNames = new HashSet<string>(projects.Where(p => p.Player).Select(p => p.Assembly.name));
            var responseFiles = new Dictionary<string, ResponseFileData>();
            var written = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach (var p in projects)
            {
                var path = Path.Combine(ProjectDirectory, p.Name + ".csproj");
                Write(path, Csproj(p, p.Player ? playerNames : editorNames, responseFiles));
                written.Add(path);
            }
            Write(SolutionPath, Solution(projects));
            DeleteStale(written);
        }

        static IEnumerable<Project> Projects(AssembliesType type, string suffix) =>
            CompilationPipeline.GetAssemblies(type)
                .Where(a => a.sourceFiles.Length > 0 && IsUserCode(a))
                .Select(a => new Project { Name = a.name + suffix, Assembly = a, Player = type == AssembliesType.Player });

        /// <summary>Scripts in Assets, or in packages of the sources picked in External Tools; other packages are referenced as DLLs.</summary>
        static bool IsUserCode(Assembly a)
        {
            var first = a.sourceFiles[0].Replace('\\', '/');
            if (first.StartsWith("Assets/", StringComparison.Ordinal)) return true;
            if (!first.StartsWith("Packages/", StringComparison.Ordinal)) return false;
            return Settings.Generates(Package(first)?.source);
        }

        /// <summary>
        /// Projects a previous sync wrote that are gone now (a package source
        /// or player projects turned off, an assembly removed). Only files with
        /// Haze's marker are touched.
        /// </summary>
        static void DeleteStale(HashSet<string> written)
        {
            foreach (var path in Directory.GetFiles(ProjectDirectory, "*.csproj"))
            {
                if (written.Contains(path)) continue;
                try
                {
                    if (File.ReadAllText(path).Contains(k_Marker)) File.Delete(path);
                }
                catch (IOException) { }
            }
        }

        static string Csproj(Project p, HashSet<string> generated, Dictionary<string, ResponseFileData> responseFiles)
        {
            var a = p.Assembly;
            var options = a.compilerOptions;
            var rsp = (options.ResponseFiles ?? new string[0]).Select(f => ParseResponseFile(f, options, responseFiles)).ToArray();
            var args = Arguments(rsp.SelectMany(r => r.OtherArguments).Concat(options.AdditionalCompilerArguments ?? new string[0]));

            var defines = a.defines
                .Concat(rsp.SelectMany(r => r.Defines))
                .Concat(List(args, "define", "d"))
                .Distinct();
            var nowarn = new List<string> { "MSB3277" };
            if (PlayerSettings.suppressCommonWarnings) nowarn.AddRange(new[] { "0169", "0649" });
            nowarn.AddRange(List(args, "nowarn"));
            var unsafeCode = options.AllowUnsafeCode || rsp.Any(r => r.Unsafe) || (args.Contains("unsafe") && args["unsafe"].Last() != "-");
            var langVersion = args["langversion"].LastOrDefault();
            if (string.IsNullOrEmpty(langVersion)) langVersion = string.IsNullOrEmpty(options.LanguageVersion) ? "latest" : options.LanguageVersion;
            var ruleset = args["ruleset"].Append(options.RoslynAnalyzerRulesetPath).LastOrDefault(s => !string.IsNullOrEmpty(s));
            var analyzerConfig = Option<string>(options, "AnalyzerConfigPath");

            var x = new StringBuilder();
            x.AppendLine("<Project ToolsVersion=\"Current\">");
            x.AppendLine("  " + k_Marker);
            x.AppendLine("  <PropertyGroup>");
            x.AppendLine("    <BaseIntermediateOutputPath>Temp/obj/$(Configuration)/$(MSBuildProjectName)/</BaseIntermediateOutputPath>");
            x.AppendLine("    <IntermediateOutputPath>$(BaseIntermediateOutputPath)</IntermediateOutputPath>");
            x.AppendLine("  </PropertyGroup>");
            x.AppendLine("  <Import Project=\"Sdk.props\" Sdk=\"Microsoft.NET.Sdk\" />");
            x.AppendLine("  <PropertyGroup>");
            x.AppendLine("    <TargetFramework>netstandard2.1</TargetFramework>");
            x.AppendLine($"    <AssemblyName>{Esc(a.name)}</AssemblyName>");
            x.AppendLine($"    <RootNamespace>{Esc(a.rootNamespace)}</RootNamespace>");
            x.AppendLine($"    <LangVersion>{Esc(langVersion)}</LangVersion>");
            x.AppendLine("    <OutputType>Library</OutputType>");
            x.AppendLine(p.Player ? "    <OutputPath>Temp/bin/$(Configuration)/Player/</OutputPath>" : "    <OutputPath>Temp/bin/$(Configuration)/</OutputPath>");
            x.AppendLine("    <AppendTargetFrameworkToOutputPath>false</AppendTargetFrameworkToOutputPath>");
            x.AppendLine("    <EnableDefaultItems>false</EnableDefaultItems>");
            x.AppendLine("    <GenerateAssemblyInfo>false</GenerateAssemblyInfo>");
            x.AppendLine("    <DisableImplicitFrameworkReferences>true</DisableImplicitFrameworkReferences>");
            x.AppendLine("    <NoStdLib>true</NoStdLib>");
            x.AppendLine("    <NoConfig>true</NoConfig>");
            x.AppendLine("    <ImplicitUsings>disable</ImplicitUsings>");
            x.AppendLine($"    <Nullable>{Esc(Nullable(args["nullable"].LastOrDefault()))}</Nullable>");
            x.AppendLine($"    <AllowUnsafeBlocks>{unsafeCode}</AllowUnsafeBlocks>");
            x.AppendLine($"    <DefineConstants>{Esc(string.Join(";", defines))}</DefineConstants>");
            x.AppendLine($"    <NoWarn>{Esc(string.Join(";", nowarn.Distinct()))}</NoWarn>");
            AppendWarningsAsErrors(x, args);
            if (!string.IsNullOrEmpty(ruleset))
                x.AppendLine($"    <CodeAnalysisRuleSet>{Esc(Resolve(ruleset))}</CodeAnalysisRuleSet>");
            x.AppendLine("  </PropertyGroup>");

            x.AppendLine("  <ItemGroup>");
            foreach (var file in a.sourceFiles)
                x.AppendLine($"    <Compile Include=\"{Esc(Relative(file))}\" />");
            x.AppendLine("  </ItemGroup>");

            var analyzers = Analyzers(options, args);
            var additionalFiles = List(args, "additionalfile")
                .Concat(Option<string[]>(options, "RoslynAdditionalFilePaths") ?? new string[0])
                .Select(Resolve).Distinct().ToArray();
            if (analyzers.Length + additionalFiles.Length > 0 || !string.IsNullOrEmpty(analyzerConfig))
            {
                x.AppendLine("  <ItemGroup>");
                foreach (var dll in analyzers)
                    x.AppendLine($"    <Analyzer Include=\"{Esc(dll)}\" />");
                foreach (var file in additionalFiles)
                    x.AppendLine($"    <AdditionalFiles Include=\"{Esc(file)}\" />");
                if (!string.IsNullOrEmpty(analyzerConfig))
                    x.AppendLine($"    <GlobalAnalyzerConfigFiles Include=\"{Esc(Resolve(analyzerConfig))}\" />");
                x.AppendLine("  </ItemGroup>");
            }

            x.AppendLine("  <ItemGroup>");
            var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach (var r in a.assemblyReferences.Where(r => !generated.Contains(r.name)))
                AppendReference(x, seen, r.name, r.outputPath);
            foreach (var dll in a.compiledAssemblyReferences.Concat(rsp.SelectMany(r => r.FullPathReferences)))
                AppendReference(x, seen, Path.GetFileNameWithoutExtension(dll), dll);
            x.AppendLine("  </ItemGroup>");

            var projects = a.assemblyReferences.Where(r => generated.Contains(r.name)).ToArray();
            if (projects.Length > 0)
            {
                var suffix = p.Player ? ".Player" : "";
                x.AppendLine("  <ItemGroup>");
                foreach (var r in projects)
                    x.AppendLine($"    <ProjectReference Include=\"{Esc(r.name + suffix)}.csproj\" />");
                x.AppendLine("  </ItemGroup>");
            }

            x.AppendLine("  <Import Project=\"Sdk.targets\" Sdk=\"Microsoft.NET.Sdk\" />");
            x.AppendLine("</Project>");
            return x.ToString();
        }

        static ResponseFileData ParseResponseFile(string path, ScriptCompilerOptions options, Dictionary<string, ResponseFileData> cache)
        {
            var key = path + ":" + (int)options.ApiCompatibilityLevel;
            if (cache.TryGetValue(key, out var data)) return data;
            data = CompilationPipeline.ParseResponseFile(path, ProjectDirectory,
                CompilationPipeline.GetSystemAssemblyDirectories(options.ApiCompatibilityLevel));
            foreach (var error in data.Errors)
                Debug.LogWarning($"Haze: {path}: {error}");
            return cache[key] = data;
        }

        /// <summary>
        /// Compiler options by lowercase name: "-nowarn:0168" is ("nowarn",
        /// "0168"), "-nullable+" is ("nullable", "+"), "-unsafe" is ("unsafe", "").
        /// </summary>
        static ILookup<string, string> Arguments(IEnumerable<string> args) =>
            args.Where(s => s.Length > 1 && (s[0] == '-' || s[0] == '/'))
                .Select(s =>
                {
                    var body = s.Substring(1);
                    var colon = body.IndexOf(':');
                    if (colon > 0) return (key: body.Substring(0, colon).ToLowerInvariant(), value: body.Substring(colon + 1).Trim('"'));
                    var last = body[body.Length - 1];
                    if (last == '+' || last == '-') return (key: body.Substring(0, body.Length - 1).ToLowerInvariant(), value: last.ToString());
                    return (key: body.ToLowerInvariant(), value: "");
                })
                .ToLookup(o => o.key, o => o.value);

        /// <summary>The values of list options such as "-nowarn:a,b" or "-define:A;B".</summary>
        static IEnumerable<string> List(ILookup<string, string> args, params string[] keys) =>
            keys.SelectMany(k => args[k])
                .SelectMany(v => v.Split(new[] { ',', ';' }, StringSplitOptions.RemoveEmptyEntries))
                .Select(v => v.Trim())
                .Where(v => v.Length > 0);

        static string Nullable(string value)
        {
            if (value == null) return "disable";
            if (value == "" || value == "+") return "enable";
            if (value == "-") return "disable";
            return value;
        }

        /// <summary>"-warnaserror[+|-]" for all warnings, "-warnaserror[+]:ids" and "-warnaserror-:ids" for some.</summary>
        static void AppendWarningsAsErrors(StringBuilder x, ILookup<string, string> args)
        {
            var all = args["warnaserror"].Where(v => v == "" || v == "+" || v == "-").LastOrDefault();
            if (all != null)
                x.AppendLine($"    <TreatWarningsAsErrors>{all != "-"}</TreatWarningsAsErrors>");
            var ids = args["warnaserror"].Where(v => v.Length > 1)
                .Concat(args["warnaserror+"])
                .SelectMany(v => v.Split(',', ';')).Where(v => v.Length > 0).Distinct().ToArray();
            if (ids.Length > 0)
                x.AppendLine($"    <WarningsAsErrors>{Esc(string.Join(";", ids))}</WarningsAsErrors>");
            var notIds = List(args, "warnaserror-").Distinct().ToArray();
            if (notIds.Length > 0)
                x.AppendLine($"    <WarningsNotAsErrors>{Esc(string.Join(";", notIds))}</WarningsNotAsErrors>");
        }

        /// <summary>The project's analyzers, plus the bundled Microsoft.Unity.Analyzers unless turned off or already there.</summary>
        static string[] Analyzers(ScriptCompilerOptions options, ILookup<string, string> args)
        {
            var analyzers = (options.RoslynAnalyzerDllPaths ?? new string[0])
                .Concat(List(args, "analyzer", "a"))
                .Select(Resolve)
                .Distinct()
                .ToList();
            var bundled = s_UnityAnalyzers;
            if (bundled != null && !analyzers.Any(d => Path.GetFileName(d).Equals(Path.GetFileName(bundled), StringComparison.OrdinalIgnoreCase)))
                analyzers.Add(bundled);
            return analyzers.ToArray();
        }

        /// <summary>Microsoft.Unity.Analyzers when turned on, found once per sync.</summary>
        static string s_UnityAnalyzers;

        static string BundledUnityAnalyzers()
        {
            var package = PackageInfo.FindForAssembly(typeof(ProjectGeneration).Assembly);
            if (package == null || string.IsNullOrEmpty(package.resolvedPath)) return null;
            var dll = Path.Combine(package.resolvedPath, "Analyzers~", "Microsoft.Unity.Analyzers.dll");
            return File.Exists(dll) ? Path.GetFullPath(dll) : null;
        }

        /// <summary>Packages by "Packages/name": every source file and reference asks, and Unity's lookup is slow.</summary>
        static readonly Dictionary<string, PackageInfo> s_Packages = new Dictionary<string, PackageInfo>(StringComparer.Ordinal);

        static PackageInfo Package(string assetPath)
        {
            var end = assetPath.IndexOf('/', "Packages/".Length);
            var root = end < 0 ? assetPath : assetPath.Substring(0, end);
            if (!s_Packages.TryGetValue(root, out var package))
                s_Packages[root] = package = PackageInfo.FindForAssetPath(root);
            return package;
        }

        /// <summary>A compiler option newer than the oldest supported Unity (2021.3+), or default.</summary>
        static T Option<T>(ScriptCompilerOptions options, string name) where T : class =>
            typeof(ScriptCompilerOptions).GetProperty(name)?.GetValue(options) as T;

        static void AppendReference(StringBuilder x, HashSet<string> seen, string name, string path)
        {
            if (!seen.Add(name)) return;
            x.AppendLine($"    <Reference Include=\"{Esc(name)}\">");
            x.AppendLine($"      <HintPath>{Esc(Resolve(path))}</HintPath>");
            x.AppendLine("      <Private>false</Private>");
            x.AppendLine("    </Reference>");
        }

        static string Solution(IEnumerable<Project> projects)
        {
            const string sdkCsharp = "{9A19103F-16F7-4668-BE54-9A1E7A4F7556}";
            var guids = projects.Select(p => (name: p.Name, guid: Guid(p.Name))).ToArray();
            var x = new StringBuilder();
            x.AppendLine();
            x.AppendLine("Microsoft Visual Studio Solution File, Format Version 12.00");
            x.AppendLine("# Visual Studio Version 17");
            foreach (var (name, guid) in guids)
            {
                x.AppendLine($"Project(\"{sdkCsharp}\") = \"{name}\", \"{name}.csproj\", \"{guid}\"");
                x.AppendLine("EndProject");
            }
            x.AppendLine("Global");
            x.AppendLine("\tGlobalSection(SolutionConfigurationPlatforms) = preSolution");
            x.AppendLine("\t\tDebug|Any CPU = Debug|Any CPU");
            x.AppendLine("\tEndGlobalSection");
            x.AppendLine("\tGlobalSection(ProjectConfigurationPlatforms) = postSolution");
            foreach (var (_, guid) in guids)
            {
                x.AppendLine($"\t\t{guid}.Debug|Any CPU.ActiveCfg = Debug|Any CPU");
                x.AppendLine($"\t\t{guid}.Debug|Any CPU.Build.0 = Debug|Any CPU");
            }
            x.AppendLine("\tEndGlobalSection");
            x.AppendLine("EndGlobal");
            return x.ToString();
        }

        /// <summary>A stable project GUID, so the .sln does not change between syncs.</summary>
        static string Guid(string name)
        {
            using (var md5 = MD5.Create())
            {
                var hash = md5.ComputeHash(Encoding.UTF8.GetBytes(name));
                return new System.Guid(hash).ToString("B").ToUpperInvariant();
            }
        }

        /// <summary>
        /// The real path of an asset path: "Packages/name/..." is virtual and
        /// points into the package cache or a local package anywhere on disk.
        /// </summary>
        public static string Resolve(string path)
        {
            var unity = path.Replace('\\', '/');
            if (unity.StartsWith("Packages/", StringComparison.Ordinal))
            {
                var package = Package(unity);
                if (package != null && !string.IsNullOrEmpty(package.resolvedPath))
                {
                    var rest = unity.Substring(package.assetPath.Length).TrimStart('/');
                    return Path.GetFullPath(Path.Combine(package.resolvedPath, rest));
                }
            }
            return Path.GetFullPath(Path.Combine(ProjectDirectory, path));
        }

        static string Relative(string path)
        {
            var full = Resolve(path);
            var root = ProjectDirectory + Path.DirectorySeparatorChar;
            return (full.StartsWith(root, StringComparison.Ordinal) ? full.Substring(root.Length) : full).Replace('\\', '/');
        }

        static string Esc(string s) => SecurityElement.Escape(s ?? "");

        /// <summary>Writes only when the content changed, so the language server does not reload for nothing.</summary>
        static void Write(string path, string content)
        {
            if (File.Exists(path) && File.ReadAllText(path) == content) return;
            File.WriteAllText(path, content, new UTF8Encoding(false));
        }
    }
}
